type Ctx = {
  theme: ThemeMode; resolvedTheme: "light" | "dark"; setTheme: (m: ThemeMode) => void;
  view: ViewMode; setView: (v: ViewMode) => void;
  locale: Locale; setLocale: (l: Locale) => void; t: (k: string) => string;
};
const ExpCtx = createContext<Ctx | null>(null);

function read<T extends string>(key: string, ok: readonly string[], fallback: T): T {
  try { const v = localStorage.getItem(key); if (v && ok.includes(v)) return v as T; } catch { /* ignore */ }
  return fallback;
}

export function NexusExperienceProvider({ children }: { children: ReactNode }) {
  const [theme, setThemeState] = useState<ThemeMode>(() => read(THEME_KEY, ["system", "light", "dark"], "system"));
  const [sysDark, setSysDark] = useState(() => typeof window !== "undefined" && !!window.matchMedia?.("(prefers-color-scheme: dark)").matches);
  const [view, setViewState] = useState<ViewMode>(() => read(VIEW_KEY, ["simple", "standard", "pro"], "simple"));
  const [locale, setLocaleState] = useState<Locale>(() => read(LOCALE_KEY, LOCALES, "zh-TW"));

  useEffect(() => { applyTheme(theme); try { localStorage.setItem(THEME_KEY, theme); } catch { /* */ } }, [theme]);
  useEffect(() => { try { localStorage.setItem(VIEW_KEY, view); } catch { /* */ } }, [view]);
  useEffect(() => { document.documentElement.lang = locale; try { localStorage.setItem(LOCALE_KEY, locale); } catch { /* */ } }, [locale]);
  useEffect(() => {
    const mq = window.matchMedia?.("(prefers-color-scheme: dark)"); if (!mq) return;
    const h = () => setSysDark(mq.matches); mq.addEventListener?.("change", h); return () => mq.removeEventListener?.("change", h);
  }, []);

  const resolvedTheme = theme === "system" ? (sysDark ? "dark" : "light") : theme;
  const t = useCallback((k: string) => M[locale][k] ?? M["zh-TW"][k] ?? k, [locale]);
  const value = useMemo<Ctx>(() => ({
    theme, resolvedTheme, setTheme: setThemeState, view, setView: setViewState,
    locale, setLocale: setLocaleState, t,
  }), [theme, resolvedTheme, view, locale, t]);
  return <ExpCtx.Provider value={value}>{children}</ExpCtx.Provider>;
}

export function useExperience(): Ctx {
  const c = useContext(ExpCtx);
  if (!c) throw new Error("useExperience requires NexusExperienceProvider");
  return c;
}
